#!/usr/bin/env python3
"""Derives pause_menu_achievements_as.h from pause_menu_as.h (as2c's output of pause_menu.as).

The Android build (no photo mode there) shows an Achievements row where the START menu has Photo
Mode: the same script with the row's label and the message it sends changed:
    "Photo Mode"          -> "Achievements"
    "DAORecomp.PhotoMode" -> "DAORecomp.Achievements"
Each is an ActionPush of one string, so a change grows that action and the script's one enclosing
DefineFunction2 (its code size); no jump crosses these (checked below). Run from DAORecomp/ui:
    python3 make_pause_menu_achievements.py
"""
import re
import struct

SRC, DST, NAME = 'pause_menu_as.h', 'pause_menu_achievements_as.h', 'kPauseMenuAchievementsScript'
CHANGES = [(b'Photo Mode', b'Achievements'), (b'DAORecomp.PhotoMode', b'DAORecomp.Achievements')]


def load():
    text = open(SRC).read()
    m = re.search(r'kPauseMenuScript\[\] = \{(.*?)\};', text, re.S)
    return bytes(int(x, 16) for x in re.findall(r'0x([0-9A-Fa-f]{2})', m.group(1)))


def actions(b, start, end, depth, out, funcs):
    i = start
    while i < end:
        code = b[i]
        if code < 0x80:
            out.append((i, code, 0))
            i += 1
            continue
        length = struct.unpack_from('<H', b, i + 1)[0]
        out.append((i, code, length))
        body = i + 3
        if code == 0x8E:  # DefineFunction2: name, params, register count, flags, parameters, code size
            p = b.index(0, body) + 1
            n = struct.unpack_from('<H', b, p)[0]
            p += 2 + 1 + 2
            for _ in range(n):
                p = b.index(0, p + 1) + 1
            size = struct.unpack_from('<H', b, p)[0]
            funcs.append((i, p, size))
            i = body + length
            actions(b, i, i + size, depth + 1, out, funcs)
            i += size
            continue
        i = body + length


def main():
    script = bytearray(load())
    out0, funcs0 = [], []
    actions(script, 0, len(script), 0, out0, funcs0)
    funcs0_end = funcs0[0][1] + 2 + funcs0[0][2]
    for old, new in CHANGES:
        out, funcs = [], []
        actions(script, 0, len(script), 0, out, funcs)
        hits = [(i, ln) for i, code, ln in out
                if code == 0x96 and ln == len(old) + 2 and script[i + 3] == 0 and script[i + 4:i + 3 + ln - 1] == old]
        assert len(hits) == 1, (old, hits)
        at, length = hits[0]
        delta = len(new) - len(old)
        # Jumps (ActionJump 0x99, ActionIf 0x9D: signed offset from the next action) must not cross it.
        for i, code, ln in out:
            if code in (0x99, 0x9D):
                target = i + 5 + struct.unpack_from('<h', script, i + 3)[0]
                assert not (min(i + 5, target) <= at < max(i + 5, target)), 'a jump crosses the change'
        enclosing = [f for f in funcs if f[0] < at < f[0] + 3 + 0xFFFF and f[2] and
                     (lambda body_start: body_start <= at < body_start + f[2])(f[1] + 2)]
        assert len(enclosing) == 1, enclosing  # only the outermost function holds these strings
        # The push's body is the type byte (0: string), the string and its NUL.
        script[at + 3:at + 3 + length] = b'\x00' + new + b'\x00'
        script[at + 1:at + 3] = struct.pack('<H', length + delta)
        f = enclosing[0]
        script[f[1]:f[1] + 2] = struct.pack('<H', f[2] + delta)
    # Check: the script grew by what the strings did, and the outer function still ends where
    # the original's did (plus that).
    grown = sum(len(n) - len(o) for o, n in CHANGES)
    out, funcs = [], []
    actions(script, 0, len(script), 0, out, funcs)
    assert len(script) == len(load()) + grown
    assert funcs[0][1] + 2 + funcs[0][2] == funcs0_end + grown
    lines = []
    for k in range(0, len(script), 16):
        lines.append('    ' + ', '.join('0x%02X' % x for x in script[k:k + 16]) + ',')
    open(DST, 'w').write(
        '// Generated by make_pause_menu_achievements.py from pause_menu_as.h; do not edit.\n'
        '// The START menu script with an Achievements row where Photo Mode is (Android).\n'
        '#pragma once\n#include <cstdint>\n\n'
        'inline constexpr uint8_t %s[] = {\n%s\n};\n' % (NAME, '\n'.join(lines)))
    print(len(script), 'bytes written to', DST)


if __name__ == '__main__':
    main()
